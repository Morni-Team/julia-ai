function t(sprachcode, schluessel, werte) {
  const tabelle = TEXTE[sprachcode] || TEXTE.de;
  let s = tabelle[schluessel] ?? TEXTE.de[schluessel] ?? schluessel;
  if (werte) for (const [k, v] of Object.entries(werte)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

